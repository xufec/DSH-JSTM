def _dict_body(src, var):
    """★ R243：取 `_VAR = { … }` 的**括号配对**内容（**不用正则**）。

    ★★ 为什么必须换掉正则：旧实现是
        `re.search(var + r'\\s*=\\s*\\{(.*?)\\n\\}', src, re.S)`
      它要求字典以 **行首的 `}`** 结束 —— 而 `_R171`/`_R172` 是**单行**字典，
      于是这个正则**跨过了 `_R171` 一直吃到"文件里第一个 `\\n}`"**。
      R243 在 `_R171` 与 `_R172` 之间插入了一个**多行字典**（`_RANK_METRIC`）
      ⇒ 匹配终点突然变成那个字典 ⇒ **`_R172` 的 10 条与 `12918/12994` 全被误报**
      （门禁当场把这次改动"抓"成了 FAIL —— 但**错的是门禁的解析器**）。
    """
    m = re.search(r'(?m)^%s\s*=\s*\{' % re.escape(var), src)
    if not m:
        return ''
    i = src.index('{', m.start())
    depth = 0
    for j in range(i, len(src)):
        c = src[j]
        if c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                return src[i + 1:j]
    return ''


def static_present(cmd, src):
    """★ 静态：`if cmd == N:` / `if cmd in (…N…)` / ★ **`if cmd in _VAR:`（变量集合）**。

    最后一类是 R171 引入的（`if cmd in _R171:` 数据驱动）——
    门禁 G 第一版**只认字面量元组** ⇒ 把 R171 的 21 条**误报**为"不在任何 `if cmd` 里"。
    """
    if re.search(r'if cmd == %d:' % cmd, src):
        return True
    for mm in re.finditer(r'if cmd in \(([^)]*)\):', src, re.S):
        if cmd in [int(x) for x in re.findall(r'\b(\d{4,6})\b', mm.group(1))]:
            return True
    # ★ `if cmd in _VAR:` ⇒ 去 `_VAR = { … }` 的键里找（**括号配对**，见 `_dict_body`）
    for mm in re.finditer(r'if cmd in (_[A-Za-z0-9_]+):', src):
        body = _dict_body(src, mm.group(1))
        if body and re.search(r'\b%d\s*:' % cmd, body):
            return True
    return False


