#!/usr/bin/env python3
"""Generate server/proto_defs.py from protocol/fields.json.

The generated module is the single source of truth for the Phase-2 server:
every message (CS*/SC*/Dsc*) with its command id, direction and typed fields.
"""
import os, json, collections

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, 'protocol', 'fields.json')
OUT = os.path.join(HERE, 'proto_defs.py')


def main():
    msgs = json.load(open(SRC, encoding='utf-8'))
    entries = {}
    skipped = 0
    for name, v in sorted(msgs.items()):
        if not v.get('fields'):
            continue
        try:
            cmd = int(v['cmd'])
        except (TypeError, ValueError):
            skipped += 1
            continue
        fields = []
        for f in v['fields']:
            if f['type'] == 'table' and 'items' in f:
                sub = '; '.join('%s:%s' % (i['name'], i['type']) for i in f['items'])
                fields.append((f['name'], 'table', sub))
            else:
                fields.append((f['name'], f['type'], ''))
        entries[name] = {'cmd': cmd, 'dir': v['dir'] or '?', 'fields': fields}

    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('"""Auto-generated by server/gen_proto_defs.py -- DO NOT EDIT.\n\n'
                'Source: protocol/fields.json (extracted from the client bytecode).\n'
                'fields: (name, type, sub) where type in\n'
                '    uint8 int8 uint16 int16 uint32 int32 string float double bool table\n'
                '    table entries carry a "sub" string of sub-fields: name:type;name:type\n'
                '"""\n\n')
        f.write('MESSAGES = {\n')
        for name, v in entries.items():
            f.write('    %r: {\n' % name)
            f.write('        "cmd": %d,\n' % v['cmd'])
            f.write('        "dir": %r,\n' % v['dir'])
            f.write('        "fields": [\n')
            for fn, ft, sub in v['fields']:
                f.write('            (%r, %r, %r),\n' % (fn, ft, sub))
            f.write('        ],\n    },\n')
        f.write('}\n\n')
        by_cmd = collections.defaultdict(list)
        for name, v in entries.items():
            by_cmd[v['cmd']].append(name)
        f.write('BY_CMD = {\n')
        for cmd in sorted(by_cmd, key=lambda x: (len(str(x)), x)):
            f.write('    %d: %r,\n' % (cmd, sorted(by_cmd[cmd])))
        f.write('}\n\n')
        f.write('def cs_name(cmd):\n'
                '    """client->server class name for a command id (or None)."""\n'
                '    for n in BY_CMD.get(cmd, ()):\n'
                '        if n.startswith("CS"):\n'
                '            return n\n'
                '    return None\n\n')
        f.write('def sc_name(cmd):\n'
                '    """server->client class name for a command id (or None)."""\n'
                '    for n in BY_CMD.get(cmd, ()):\n'
                '        if n.startswith("SC"):\n'
                '            return n\n'
                '    return None\n')
    print('generated %s : %d messages, %d commands (%d skipped: no numeric cmd)'
          % (OUT, len(entries), len({v['cmd'] for v in entries.values()}), skipped))


if __name__ == '__main__':
    main()